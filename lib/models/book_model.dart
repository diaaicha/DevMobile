class Book {
  final String id;
  final String title;
  final int price;
  final String image;
  final String category;
  final String description;
  final String author;
  final double rating;

  Book({
    required this.id,
    required this.title,
    required this.price,
    required this.image,
    required this.category,
    required this.description,
    required this.author,
    required this.rating,
  });
}
